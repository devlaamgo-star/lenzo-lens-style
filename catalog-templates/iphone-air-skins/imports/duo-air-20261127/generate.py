# Regenerates src/data/iphone-air-duo-batch.ts from products.json (rerunnable; records keyed by import_key).
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "products.json")))
prods = sorted(d["products"], key=lambda p: p["sort_order"])
imports, n, out = [], 0, []
def ref(path):
    global n
    v = f"a{n}"; n += 1
    imports.append(f'import {v} from "@/assets/air/duo-air/{path[len("products/"):]}.asset.json";')
    return v
J = lambda s: json.dumps(s, ensure_ascii=False)
for i, p in enumerate(prods):
    gal = [ref(im["path"]) for im in sorted(p["images"], key=lambda x: x["position"])]
    assert p["images"][0]["path"] == p["primary_image"]
    resp = [r for r in p["primary_image_responsive"] if "_responsive" in r["path"]]
    rv = [(ref(r["path"]), r["width"]) for r in resp]
    cover = ", ".join([f"{{ url: {v}.url, width: {w}, height: {w} }}" for v, w in rv] + [f"{{ url: {gal[0]}.url, width: 1200, height: 1200 }}"])
    desc = J(p["description_fr"])
    out.append(f"""  {{
    id: {J(p['import_key'])}, importKey: {J(p['import_key'])}, sku: {J(p['sku'])}, slug: {J(p['slug'])}, sortOrder: {p['sort_order']},
    name: {{ fr: {J(p['name'])}, en: {J(p['name'])}, ar: {J(p['name'])} }},
    description: {{ fr: {desc}, en: {desc}, ar: {desc} }},
    image: {gal[0]}.url, gallery: [{", ".join(g + ".url" for g in gal)}],
    responsiveCover: [{cover}], altFr: {J(p['alt_fr'])},
    category: "iphone-air-skins", device: "iPhone Air", inStock: true, isNew: false, popularity: {len(prods) - i},
  }},""")
src = "// Generated by catalog-templates/iphone-air-skins/imports/duo-air-20261127/generate.py — do not edit by hand.\n"
src += 'import type { IphoneAirSkin } from "./iphone-air-skins";\n' + "\n".join(imports)
src += "\n\nexport const DUO_AIR_SKINS: IphoneAirSkin[] = [\n" + "\n".join(out) + "\n];\n"
open(os.path.join(here, "../../../../src/data/iphone-air-duo-batch.ts"), "w").write(src)
print(len(prods), n)
