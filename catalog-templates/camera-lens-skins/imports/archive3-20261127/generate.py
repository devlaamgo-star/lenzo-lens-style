"""Generate the additive code-backed catalog; keep UUIDs stable across reruns."""
import hashlib
import json
from pathlib import Path
import uuid

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
ASSETS = ROOT / 'src/assets/lens/archive3'
OUTPUT = ROOT / 'src/data/camera-lens-archive3.ts'

def generate():
    products = sum([json.loads((HERE / f'CATALOG_PART_{i}.json').read_text())['products'] for i in (1, 2)], [])
    assert len(products) == 40
    assert sum(p['image_count'] for p in products) == 197
    for field in ('import_key', 'sku', 'slug'):
        assert len({p[field] for p in products}) == 40
    identity_file = HERE / 'identities.json'
    identities = json.loads(identity_file.read_text()) if identity_file.exists() else {}
    previous_by_sku = {record['sku']: record['id'] for record in identities.values()}
    lines = ['// Generated by the saved archive3 import script. Do not edit by hand.',
             'import { CAMERA_ONLY_NOTE, type CameraLensSkin } from "./camera-lens-types";']
    records = []
    paths = set()
    for n, p in enumerate(products):
        key = p['import_key']
        record_id = identities.get(key, {}).get('id') or previous_by_sku.get(p['sku']) or str(uuid.uuid4())
        uuid.UUID(record_id)
        identities[key] = {'id': record_id, 'sku': p['sku']}
        images = sorted(p['images'], key=lambda im: im['position'])
        assert len(images) == p['image_count']
        assert [im['position'] for im in images] == list(range(1, len(images) + 1))
        assert images[0]['path'] == p['primary_image']
        assert images[0]['path'].endswith('-01-cover.webp')
        assert sum(im['is_primary'] for im in images) == 1
        refs = []
        for j, im in enumerate(images):
            assert str(Path(im['path']).parent) == p['folder']
            assert im['path'] not in paths
            paths.add(im['path'])
            filename = Path(im['path']).name
            pointer = ASSETS / (filename + '.asset.json')
            asset = json.loads(pointer.read_text())
            assert asset['original_filename'] == filename and asset['size'] == im['bytes']
            ref = f'asset{n}_{j}'
            refs.append(ref + '.url')
            lines.append(f'import {ref} from "../assets/lens/archive3/{filename}.asset.json";')
        name = json.dumps({lang: p['name'] for lang in ('fr', 'en', 'ar')}, ensure_ascii=False)
        description = json.dumps({lang: '' for lang in ('fr', 'en', 'ar')})
        records.append('  {\n' +
            f'    id: {json.dumps(record_id)}, importKey: {json.dumps(key)}, sku: {json.dumps(p["sku"])}, slug: {json.dumps(p["slug"])}, sortOrder: {73+n},\n' +
            f'    name: {name}, description: {description},\n' +
            f'    image: {refs[0]}, gallery: [{", ".join(refs)}],\n' +
            f'    imageWidth: {images[0]["width"]}, imageHeight: {images[0]["height"]}, altFr: {json.dumps(images[0]["alt"], ensure_ascii=False)},\n' +
            '    category: "camera-lens-skins", device: "iPhone 17 Pro Max", inStock: true, isNew: false,\n' +
            '    popularity: 0, imagePresentation: "full-phone", scopeNote: CAMERA_ONLY_NOTE,\n  },')
    identity_file.write_text(json.dumps(identities, indent=2, ensure_ascii=False) + '\n')
    OUTPUT.write_text('\n'.join(lines) + '\n\nexport const ARCHIVE3_CAMERA_SKINS: CameraLensSkin[] = [\n' + '\n'.join(records) + '\n];\n')
    print('Generated 40 products / 197 photos with persistent UUIDs')

if __name__ == '__main__':
    generate()